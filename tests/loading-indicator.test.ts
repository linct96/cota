import { afterEach, expect, it, vi } from 'vitest'
import { createLoadingIndicator } from '../src/renderer/src/lib/loading-indicator'

afterEach(() => vi.useRealTimers())

it('skips fast work, holds visible loading for 300ms, and cancels stale timers across stages and cleanup', () => {
  vi.useFakeTimers()
  const changed = vi.fn()
  const indicator = createLoadingIndicator(changed)

  indicator.update(true)
  vi.advanceTimersByTime(199)
  indicator.update(false)
  vi.advanceTimersByTime(1000)
  expect(changed).not.toHaveBeenCalled()

  indicator.update(true)
  vi.advanceTimersByTime(150)
  indicator.update(false)
  indicator.update(true)
  vi.advanceTimersByTime(49)
  expect(changed).not.toHaveBeenCalled()
  vi.advanceTimersByTime(1)
  expect(changed.mock.calls).toEqual([[true]])
  indicator.update(false)
  vi.advanceTimersByTime(299)
  expect(changed).toHaveBeenCalledTimes(1)
  vi.advanceTimersByTime(1)
  expect(changed.mock.calls).toEqual([[true], [false]])

  changed.mockClear()
  indicator.update(true)
  vi.advanceTimersByTime(200)
  indicator.update(false)
  vi.advanceTimersByTime(100)
  indicator.update(true)
  vi.advanceTimersByTime(600)
  expect(changed.mock.calls).toEqual([[true]])
  indicator.update(false)
  vi.advanceTimersByTime(0)
  expect(changed.mock.calls).toEqual([[true], [false]])

  changed.mockClear()
  indicator.update(true)
  indicator.cancel()
  vi.advanceTimersByTime(1000)
  expect(changed).not.toHaveBeenCalled()
  indicator.update(true)
  vi.advanceTimersByTime(200)
  indicator.update(false)
  indicator.cancel()
  vi.advanceTimersByTime(1000)
  expect(changed.mock.calls).toEqual([[true]])
})
