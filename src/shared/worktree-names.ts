export function worktreeBranchSegment(value: string): string {
  return value
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}_-]+/gu, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
}

export function suggestWorktreeName(
  usedNames: Iterable<string>,
  random: () => number = Math.random,
): string {
  const used = new Set(Array.from(usedNames, (name) => name.trim().toLowerCase()))
  for (let tier = 1; ; tier++) {
    const available = SPACE_NAMES.map((name) => (tier === 1 ? name : `${name}-${tier}`)).filter(
      (name) => !used.has(name),
    )
    if (available.length) return available[Math.floor(random() * available.length)]!
  }
}
